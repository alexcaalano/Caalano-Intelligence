// Phone parsing per country, display formatting, and the email rule.
import assert from 'node:assert/strict'
import { parsePhone, normPhone, formatNational, formatPhone, isEmail, PHONE_COUNTRIES, countryByDial } from '../netlify/lib/contact.mjs'

assert.equal(normPhone('0400 000 000'), '+61400000000', 'AU is the default country')
assert.equal(normPhone('(02) 9876-5432', 'AU'), '+61298765432')
assert.equal(normPhone('61400000000', 'AU'), '+61400000000', 'dial code typed without a plus')
assert.equal(normPhone('+61 400 000 000', 'US'), '+61400000000', 'a plus overrides the picked country')
assert.equal(normPhone('0061400000000'), '+61400000000')
assert.equal(normPhone('0211234567890', 'NZ'), null, 'not a valid NZ length')
assert.equal(normPhone('021 123 4567', 'NZ'), '+64211234567')
assert.equal(normPhone('(415) 555-0123', 'US'), '+14155550123')
assert.equal(normPhone('415 555 0123', 'CA'), '+14155550123')
assert.equal(normPhone('07700 900123', 'GB'), '+447700900123')
assert.equal(normPhone('9123 4567', 'SG'), '+6591234567')
assert.equal(normPhone('98765 43210', 'IN'), '+919876543210')
assert.equal(normPhone('0400000000', 'US'), null, 'US numbers have no trunk zero and need ten digits')
assert.equal(normPhone('040000000', 'AU'), null, 'one digit short')
assert.equal(normPhone('04000000000', 'AU'), null, 'one digit long')
assert.equal(normPhone('12345'), null)
assert.equal(normPhone('abc'), null)
assert.equal(normPhone(''), null)
assert.equal(normPhone('+3725551234'), '+3725551234', 'a country outside the list passes the generic rule')
assert.deepEqual(parsePhone('0400 000 000', 'AU'), { e164: '+61400000000', iso: 'AU', dial: '61', national: '400000000' })
assert.equal(countryByDial('14155550123').iso, 'US')
assert.equal(countryByDial('353871234567').iso, 'IE')

assert.equal(formatNational('0400000000', 'AU'), '0400 000 000')
assert.equal(formatNational('04000', 'AU'), '0400 0', 'partial input while typing')
assert.equal(formatNational('4155550123', 'US'), '415 555 0123')
assert.equal(formatNational('07700900123', 'GB'), '07700 900123')
assert.equal(formatPhone('+61400000000'), '+61 400 000 000')
assert.equal(formatPhone('+14155550123'), '+1 415 555 0123')
assert.equal(formatPhone('+3725551234'), '+3725551234')

assert.ok(isEmail('alex@caalanodigital.com.au'))
assert.ok(isEmail('first.last+tag@sub.example.co'))
assert.ok(!isEmail('alex@caalanodigital'), 'no top level')
assert.ok(!isEmail('alex@.com'))
assert.ok(!isEmail('alex@@example.com'))
assert.ok(!isEmail('alex example@example.com'))
assert.ok(!isEmail('.alex@example.com'))
assert.ok(!isEmail('alex@example.c'))
assert.ok(!isEmail('alex@exa_mple.com'))
assert.ok(!isEmail(''))
assert.ok(PHONE_COUNTRIES.every((c) => /^\d{1,3}$/.test(c.dial) && c.len.length && c.groups.length))
console.log('contact_test: ok')
